CREATE TABLE resources
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_bucket VARCHAR(255)  NOT NULL,
    object_key     VARCHAR(1024) NOT NULL,
    state VARCHAR(16) NOT NULL,
    promotion_target_bucket VARCHAR(255),
    promotion_target_key VARCHAR(1024),
    cleanup_source_bucket VARCHAR(255),
    cleanup_source_key VARCHAR(1024),
    CONSTRAINT resource_state CHECK (state IN ('STAGING','PERMANENT')),
    CONSTRAINT resource_promotion_pair CHECK ((promotion_target_bucket IS NULL) = (promotion_target_key IS NULL)),
    CONSTRAINT resource_cleanup_pair CHECK ((cleanup_source_bucket IS NULL) = (cleanup_source_key IS NULL)),
    UNIQUE (storage_bucket, object_key)
);
